-- 0015_fair_queue.sql — честная очередь: индекс под счёт заданий в работе.
--
-- Зачем: при выдаче задания Control Plane смотрит, сколько заданий автора уже
-- выполняется, и отдаёт предпочтение тому, у кого их меньше. Иначе один поток
-- запросов занимает все узлы, а остальные ждут. Подсчёт идёт по частичному
-- индексу, иначе это был бы полный проход по журналу на каждую выдачу.

CREATE INDEX IF NOT EXISTS jobs_inflight_user_idx
    ON jobs (requester_user_id)
    WHERE state IN ('claimed', 'streaming');

COMMENT ON INDEX jobs_inflight_user_idx IS
    'Задания в работе по заказчику: по этому счётчику очередь отдаёт ход тому, у кого меньше нагрузки.';
