-- 0018_job_result.sql — данные результата задания, а не только счётчики.
--
-- Зачем: чат отдаётся потоком, и ему хватает чанков. Эмбеддинги — это готовый
-- результат (набор векторов), который нельзя «достримить» по одному числу.
-- Поэтому у задания появляется поле result: узел кладёт туда ответ рантайма,
-- а обработчик API забирает его после завершения.

ALTER TABLE jobs ADD COLUMN IF NOT EXISTS result jsonb;

COMMENT ON COLUMN jobs.result IS
    'Результат нестриминговых заданий (например, эмбеддинги). Для чата пусто: ответ уходит чанками.';

-- Задания разных видов ищутся по модели и состоянию; вид нужен панели и метрикам.
CREATE INDEX IF NOT EXISTS jobs_kind_idx ON jobs (kind, created_at DESC);
