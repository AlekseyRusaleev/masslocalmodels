-- 0021_mesh_link.sql — адрес RPC-стадии для шардирования (ADR 0008).
--
-- Зачем: координатору шард-группы нужны адреса соисполнителей, а не только их
-- имена. Адрес сообщает сам узел в heartbeat: он знает, на каком интерфейсе и
-- порту поднят его ggml-rpc-server. Порт по умолчанию слушает только loopback,
-- поэтому наружу адрес выходит через туннель — в поле хранится то, что узел
-- реально объявил, и ничего не додумывается на стороне платформы.

ALTER TABLE worker_nodes ADD COLUMN IF NOT EXISTS mesh_rpc_addr text NOT NULL DEFAULT '';

COMMENT ON COLUMN worker_nodes.mesh_rpc_addr IS
    'Адрес ggml-rpc-server, объявленный узлом (host:port). Пусто — узел не участвует в шард-группе.';
