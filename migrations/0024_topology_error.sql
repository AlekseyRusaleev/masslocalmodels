-- 0024_topology_error.sql — причина, по которой группа не поднялась.
--
-- Зачем: раскладка по слоям проверяет, влезает ли модель в сумму видеопамяти
-- участников. Если не влезает, группа не создаётся, а в этой колонке остаётся
-- человеческий текст: сколько нужно, сколько есть и чего не хватает. Панель
-- показывает его вместо ошибки видеокарты, которая ничего не объясняет.

ALTER TABLE topologies ADD COLUMN IF NOT EXISTS error text NOT NULL DEFAULT '';

COMMENT ON COLUMN topologies.error IS
    'Почему группа не может подняться: не хватает памяти, нет узлов, прочее.';